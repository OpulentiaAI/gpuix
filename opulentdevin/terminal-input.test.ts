import { randomUUID } from 'node:crypto'
import { describe, expect, it, vi } from 'vitest'
import { createTerminalInput } from './terminal-input'

const identity = () => ({ ownerId: 'owner', ptyId: randomUUID(), processEpoch: 'epoch-1' })
function deferred() {
  let resolve!: () => void
  let reject!: (error: Error) => void
  const promise = new Promise<void>((yes, no) => { resolve = yes; reject = no })
  return { promise, resolve, reject }
}

describe('fail-closed terminal input', () => {
  it('never sends suffix or Enter after the first write has an unknown outcome', async () => {
    const first = deferred()
    const write = vi.fn(() => first.promise)
    const report = vi.fn()
    const input = createTerminalInput(identity(), write, report)
    input.enqueue('prefix')
    input.enqueue('suffix')
    input.enqueue('\r')
    first.reject(new Error('lost acknowledgement'))
    await input.whenIdle()
    input.enqueue('future\r')
    await input.whenIdle()
    expect(write.mock.calls).toEqual([['prefix']])
    expect(input.failed).toBe(true)
    expect(report).toHaveBeenCalled()
    input.dispose()
  })
  it('keeps a failed process latched across reselect and backend replacement', async () => {
    const id = identity()
    const first = createTerminalInput(id, async () => { throw new Error('unknown') }, vi.fn())
    first.enqueue('prefix'); await first.whenIdle(); first.dispose()
    const write = vi.fn(async () => {})
    const selectedAgain = createTerminalInput(id, write, vi.fn())
    selectedAgain.enqueue('suffix\r'); await selectedAgain.whenIdle()
    expect(selectedAgain.failed).toBe(true)
    expect(write).not.toHaveBeenCalled()
    selectedAgain.dispose()
    const newProcess = createTerminalInput({ ...id, processEpoch: 'epoch-2' }, write, vi.fn())
    newProcess.enqueue('new command\r'); await newProcess.whenIdle()
    expect(write).toHaveBeenCalledExactlyOnceWith('new command\r')
    expect(newProcess.failed).toBe(false)
    newProcess.dispose()
  })
  it('latches and drops queued bytes when unmounted during an unresolved write', async () => {
    const id = identity()
    const pending = deferred()
    const write = vi.fn(() => pending.promise)
    const input = createTerminalInput(id, write, vi.fn())
    input.enqueue('prefix'); input.enqueue('suffix'); input.enqueue('\r')
    input.dispose()
    const nextWrite = vi.fn(async () => {})
    const next = createTerminalInput(id, nextWrite, vi.fn())
    next.enqueue('\r')
    pending.resolve(); await input.whenIdle(); await next.whenIdle()
    expect(write.mock.calls).toEqual([['prefix']])
    expect(nextWrite).not.toHaveBeenCalled()
    expect(next.failed).toBe(true)
    next.dispose()
  })
  it('fails closed on queue capacity without dispatching a truncated sequence', async () => {
    const pending = deferred()
    const write = vi.fn(() => pending.promise)
    const input = createTerminalInput(identity(), write, vi.fn())
    input.enqueue('prefix'); input.enqueue('x'.repeat(65536)); input.enqueue('\r')
    pending.resolve(); await input.whenIdle()
    expect(input.failed).toBe(true)
    expect(write.mock.calls).toEqual([['prefix']])
    input.dispose()
  })
  it('drains healthy writes in order and allows an idle process to be reselected', async () => {
    const id = identity()
    const pending = deferred()
    const write = vi.fn().mockImplementationOnce(() => pending.promise).mockResolvedValue(undefined)
    const input = createTerminalInput(id, write, vi.fn())
    input.enqueue('prefix'); input.enqueue('suffix'); input.enqueue('\r')
    expect(write.mock.calls).toEqual([['prefix']])
    pending.resolve(); await input.whenIdle()
    expect(write.mock.calls).toEqual([['prefix'], ['suffix\r']])
    input.dispose()
    const next = createTerminalInput(id, write, vi.fn())
    next.enqueue('fresh'); await next.whenIdle()
    expect(write).toHaveBeenLastCalledWith('fresh')
    expect(next.failed).toBe(false)
    next.dispose()
  })
})
